export interface PromptVariables {
  tema_desc: string;      // tema principal do artigo
  angulo: string;         // ângulo específico que será utilizado
  sensacao: string;       // sensação ou reflexão que o leitor deve levar consigo
  palavra_chave: string;  // palavra-chave principal para SEO
  contador_artigo: number; // número do artigo na sequência editorial
  oferecer_ebook: boolean; // se true, incluir oferta discreta do ebook (a cada 3 artigos)
}

// Retorna true se o artigo de índice N deve oferecer o ebook (artigos 3, 6, 9...)
export function deveOfereceEbook(contadorArtigo: number): boolean {
  return contadorArtigo % 3 === 0;
}
